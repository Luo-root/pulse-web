// Package interop 是 pulse-web 的**生态互操作验证工程**（嵌套 module）。
//
// 它回答一个问题：生态里的东西经框架的适配面到底能不能用、用到什么程度。
//
// # 为什么住在嵌套 module
//
// 三件事同时成立：① 这里带**真依赖**（websocket / CORS / chi / promhttp…），主模块
// 的红线是零第三方依赖；② 对照的价值来自**能复跑**，所以必须跟主干走、进 CI——
// 待在侧分支或开发机上的采集会随上游发版**静默过期**（#73 的教训）；③ 站点要引用
// 这些结论，就得有一个稳定地址。`otel/` 与 `loadtest/` 已经把这条模式走通过。
//
// # 判据
//
// 不是「跑通了」，而是**同一个中间件、同一条路由、两个挂载点逐项一致**（对照矩阵，
// 见 #92）；协议升级这类只有一个挂载点的，判据是**真跑一次握手 + 消息往返**，
// 且访问日志里的事实必须与实际情况对得上（见 websocket_test.go）。
//
// 这里**不出**官方中间件实现：框架只给缝与配方，实现归生态（#61 的结论）。
