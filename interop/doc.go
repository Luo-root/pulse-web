// Package interop 是 pulse-web 的**生态互操作验证工程**（嵌套 module）。
//
// 它回答一个问题：生态里的东西经框架的适配面到底能不能用、用到什么程度。
//
// # 为什么住在嵌套 module
//
// 三件事同时成立：① 这里带**真依赖**（websocket / CORS / chi / promhttp…），主模块
// 的红线是零第三方依赖；② 对照的价值来自**能复跑**，所以必须跟主干走、进 CI——
// 待在侧分支或开发机上的采集会随上游发版**静默过期**（#73 的教训）；③ 站点要引用
// 这些结论，就得有一个稳定地址。`otel/` 与 `loadtest/` 已经把这条模式走通过。
//
// # 判据
//
// 不是「跑通了」，而是**同一个中间件、同一条路由，经 `Adapt` 与包在 `app.Handler()`
// 外面逐项一致**（对照矩阵，见 #92）——比三个面：响应（状态码 + 响应头 + body）、
// 中间件自己的旁观测（日志行 / 指标标签）、框架侧记下的那条访问记录。第三面单独
// 列，是因为「中间件短路」的差别恰好不在响应上（两边都返回 401）而在「框架知不知
// 道」；每一条断言之外还有一条非空断言，钉住「这个中间件真的发挥了作用」——只比
// 两侧比不出「两边都没生效」。**申报的差异也要断言**：两边本就该不同的地方写进
// `known`，申报了却一致同样报错。
//
// 协议升级这类只有一个挂载点的，判据是**真跑一次握手 + 消息往返**，且访问日志里的
// 事实必须与实际情况对得上（见 websocket_test.go）。
//
// 这里**不出**官方中间件实现：框架只给缝与配方，实现归生态（#61 的结论）。
